"""The frame of the recorded-answer scenarios (spec appendix 10, section 7).

A **scenario** is one made-up situation: one asset at one step, run through the agent's whole
decision path, with Jev's and the LLM's answers handed back from saved files (the cassettes,
by the recorder in `conftest.py`). Each names the path through the agent it covers, from the
written list in `paths.py`. `run_scenario` runs one and returns the three things each test
compares with what was saved:

- `memory_lookups`: every lookup asked of memory, in order (code's first search and track
  records, then the LLM's own);
- `orders`: the orders the step placed (the one Jev decided, or code's own: a stop price, a
  forced close, the sim's end);
- `records`: every other row the step stores, by table.

The expected results are kept with `syrupy`, in `__snapshots__/` beside the test file that runs
the scenarios; `--snapshot-update` rewrites them.

The step runs through the sim runner's own `run_step`, on the real agent, broker, Jev client and
LLM selection. The asset's bars and the memory of past episodes are generated by code
(`made_up.py`). Memory's lookups go through the real memory server code, started inside the test
and reached in-process by the MCP SDK's own `Client(server)` (no network), over the in-memory
stand-in for the database.

Every request is the same from run to run (`test_harness.py` sends one twice): Jev's options are
shuffled from the sim's random seed, and no clock time or random ID goes into anything a model
reads.

An account holding a position begins the step as a resumed sim's does (ADR 0013): the broker's
own entry opened the position some steps before, the bars since passed through the broker, and
the account is brought back from its saved state. The agent gets back the position's situation
at entry and its journal, one hold a bar. The holding sim's five purchases are made the same
way, by its own strategy at the made-up calendar's first step.

`run_scenario(scenario, bars_after=n)` then lets `n` more of the asset's bars pass, the last of
them the sim's last step, with no model asked: only the broker and the episodes' outcomes act.
The position-review outcomes test uses it.
"""

